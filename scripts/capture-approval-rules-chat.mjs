#!/usr/bin/env node
/**
 * Headless screenshots of propose_rule Confirm cards
 * (src/gallery/rule-request.html): add / change / remove, light and dark.
 * Synthetic data only. Headless Chromium: no window opens.
 * Usage: node scripts/capture-approval-rules-chat.mjs [--out DIR] [--port N]
 */
import { spawn } from "node:child_process";
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const arg = (name) => { const index = process.argv.indexOf(name); return index >= 0 ? process.argv[index + 1] : undefined; };
const outDir = resolve(arg("--out") ?? join(root, "docs", "screenshots", "approval-rules-chat"));
const port = Number(arg("--port") ?? 5311);
const skins = [{ id: "daylight", label: "light" }, { id: "pulsatrix", label: "dark" }];
const cards = [
  { card: "add", behavior: "allow", name: "add-allow" },
  { card: "add", behavior: "ask", name: "add-ask" },
  { card: "add", behavior: "deny", name: "add-deny" },
  { card: "change", behavior: "allow", name: "change-allow" },
  { card: "remove", behavior: "allow", name: "remove" },
  { card: "add", behavior: "allow", answered: "allow", name: "add-confirmed" },
];

async function waitForServer(url, ms = 120_000) {
  const start = Date.now();
  while (Date.now() - start < ms) {
    try { if ((await fetch(url)).status < 500) return; } catch { /* retry */ }
    await new Promise((done) => setTimeout(done, 500));
  }
  throw new Error(`gallery did not start at ${url}`);
}

const vite = spawn("pnpm", ["exec", "vite", "--config", "vite.gallery.config.ts", "--host", "127.0.0.1", "--port", String(port), "--strictPort"], {
  cwd: root, stdio: ["ignore", "pipe", "pipe"], env: { ...process.env, NODE_ENV: "development" },
  detached: true,
});
let log = "";
vite.stdout?.on("data", (chunk) => { log += chunk; });
vite.stderr?.on("data", (chunk) => { log += chunk; });

let browser;
try {
  const base = `http://127.0.0.1:${port}/src/gallery/rule-request.html`;
  await waitForServer(base);
  const { chromium } = await import(process.env.SAGAX_VERIFY_PLAYWRIGHT || "playwright");
  await mkdir(outDir, { recursive: true });
  browser = await chromium.launch({
    headless: true,
    ...(process.env.SAGAX_VERIFY_BROWSER_CHROME ? { executablePath: process.env.SAGAX_VERIFY_BROWSER_CHROME } : {}),
  });
  const page = await browser.newPage({ viewport: { width: 780, height: 720 }, deviceScaleFactor: 2 });
  for (const { id, label } of skins) {
    for (const shot of cards) {
      const query = new URLSearchParams({
        skin: id,
        lang: "en",
        card: shot.card,
        behavior: shot.behavior,
        ...(shot.answered ? { answered: shot.answered } : {}),
      });
      await page.goto(`${base}?${query}`, { waitUntil: "load" });
      await page.waitForSelector('[data-shot="rule-request"]');
      await page.waitForTimeout(250);
      await page.locator('[data-shot="rule-request"]').screenshot({
        path: join(outDir, `${shot.name}-${label}.png`),
      });
    }
  }
  // One-click confirm from the dock: Confirm dispatches decideRequest.
  await page.goto(`${base}?skin=daylight&lang=en&card=add&behavior=allow`, { waitUntil: "load" });
  await page.waitForSelector('[data-shot="rule-dock"]');
  await page.locator('[data-shot="rule-dock"] button').filter({ hasText: "Confirm" }).click();
  await page.waitForTimeout(200);
  const decisions = await page.evaluate(() => window.__decisions);
  await writeFile(join(outDir, "confirm-click.json"), `${JSON.stringify(decisions, null, 2)}\n`);
  await writeFile(join(outDir, "README.md"), `# Approval rules from chat

Synthetic gallery captures of \`propose_rule\` Confirm cards (add / change / remove).
Generated by \`node scripts/capture-approval-rules-chat.mjs\`.
No real person data.
`);
  console.log(`screenshots in ${outDir}`);
  console.log(`confirm click: ${JSON.stringify(decisions)}`);
} catch (error) {
  console.error(error instanceof Error ? error.message : String(error));
  if (log) console.error(log.slice(-2000));
  process.exitCode = 1;
} finally {
  await browser?.close().catch(() => {});
  try { process.kill(-vite.pid, "SIGTERM"); } catch { /* already gone */ }
}
