#!/usr/bin/env node
// Writes the phones' copy of the nothing-to-do pattern (#3990, #4551) from
// its one source, shared/routine-result.ts ROUTINE_SAYS_NOTHING_SOURCE:
// ios/Sources/CompanionCore/RoutineNothingPattern.swift and
// android/core/.../core/RoutineNothingPattern.kt. Both apps read it in
// RoutineRunRows, case-insensitive, as the desktop does.
//
//   node scripts/gen-routine-nothing-pattern.mjs          # rewrite both files
//   node scripts/gen-routine-nothing-pattern.mjs --check  # fail when one is stale
//
// shared/routine-result.test.ts fails while either file is out of date.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
export const SWIFT_FILE = join(ROOT, "ios", "Sources", "CompanionCore", "RoutineNothingPattern.swift");
export const KOTLIN_FILE = join(ROOT, "android", "core", "src", "main", "kotlin", "com", "openmausbot", "companion", "core", "RoutineNothingPattern.kt");
const HEADER = "Generated by scripts/gen-routine-nothing-pattern.mjs from shared/routine-result.ts\n// (ROUTINE_SAYS_NOTHING_SOURCE): do not edit by hand.";

/** A string literal both languages read the same way (backslashes, quotes). */
const literal = (text) => JSON.stringify(text);

export function swiftSource(pattern) {
  return `// ${HEADER}\n\n/// #3990: a run's whole summary says nothing happened (case-insensitive).\nenum RoutineNothingPattern {\n    static let source = ${literal(pattern)}\n}\n`;
}

export function kotlinSource(pattern) {
  // Kotlin reads $ in a string as a template
  return `// ${HEADER}\n\npackage com.openmausbot.companion.core\n\n/** #3990: a run's whole summary says nothing happened (case-insensitive). */\ninternal object RoutineNothingPattern {\n    const val SOURCE = ${literal(pattern).replaceAll("$", "\\$")}\n}\n`;
}

export async function expected() {
  const { ROUTINE_SAYS_NOTHING_SOURCE } = await import(pathToFileURL(join(ROOT, "shared", "routine-result.ts")).href);
  return { [SWIFT_FILE]: swiftSource(ROUTINE_SAYS_NOTHING_SOURCE), [KOTLIN_FILE]: kotlinSource(ROUTINE_SAYS_NOTHING_SOURCE) };
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  const files = await expected();
  const check = process.argv.includes("--check");
  let stale = 0;
  for (const [file, text] of Object.entries(files)) {
    let current = "";
    try { current = readFileSync(file, "utf8"); } catch { /* missing */ }
    if (current === text) continue;
    if (check) { console.error(`stale: ${file}`); stale += 1; } else writeFileSync(file, text);
  }
  if (stale) process.exit(1);
}
