#!/usr/bin/env node
/**
 * Real browser screenshots of the video widget gallery (Playwright).
 * Usage: node scripts/capture/video-widgets.mjs [--out DIR]
 */
import { spawn } from "node:child_process";
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..");
const outArg = process.argv.indexOf("--out");
const VIDEO_WIDGET_SHOTS = "docs/screenshots/video-widgets";
const outDir = outArg >= 0 ? resolve(process.argv[outArg + 1]) : join(root, VIDEO_WIDGET_SHOTS);
// Agents share the machine: the port comes from SAGAX_CAPTURE_PORT (5176-5206
// range by convention) and a real Chrome runs headless when
// SAGAX_VERIFY_BROWSER_CHROME names it. Never a visible window.
const port = String(process.env.SAGAX_CAPTURE_PORT || "5199");
const chromePath = process.env.SAGAX_VERIFY_BROWSER_CHROME || undefined;

const skins = [
  { id: "pulsatrix", label: "dark" },
  { id: "daylight", label: "light" },
];

async function waitForServer(url, ms = 120_000) {
  const start = Date.now();
  while (Date.now() - start < ms) {
    try {
      const res = await fetch(url);
      if (res.status < 500) return;
    } catch {
      /* retry */
    }
    await new Promise((r) => setTimeout(r, 500));
  }
  throw new Error(`Vite gallery did not start at ${url}`);
}

const vite = spawn(
  "pnpm",
  [
    "exec",
    "vite",
    "--config",
    "vite.gallery.config.ts",
    "--host",
    "127.0.0.1",
    "--port",
    port,
    "--strictPort",
  ],
  // own process group: pnpm exec forks vite, and killing pnpm alone left
  // vite listening on the port
  { cwd: root, detached: true, stdio: ["ignore", "pipe", "pipe"], env: { ...process.env, NODE_ENV: "development" } },
);

let viteLog = "";
vite.stdout?.on("data", (c) => { viteLog += c; });
vite.stderr?.on("data", (c) => { viteLog += c; });

try {
  const base = `http://127.0.0.1:${port}/src/gallery/video-widgets.html`;
  await waitForServer(base);
  const { chromium } = await import(process.env.SAGAX_VERIFY_PLAYWRIGHT || "playwright");
  await mkdir(outDir, { recursive: true });
  const browser = await chromium.launch({ headless: true, ...(chromePath ? { executablePath: chromePath } : {}) });
  const page = await browser.newPage({ viewport: { width: 920, height: 1400 } });

  for (const { id, label } of skins) {
    // "load", not "networkidle": the dev server keeps a socket open and the
    // sample poster is remote.
    await page.goto(`${base}?skin=${id}`, { waitUntil: "load", timeout: 120_000 });
    await page.waitForSelector(".vpc-card", { timeout: 30_000 });
    const layout = await page.locator(".vpc-top").first().evaluate((el) => {
      const top = getComputedStyle(el);
      const play = document.querySelector(".vpc-play");
      const playStyle = play ? getComputedStyle(play) : null;
      const card = document.querySelector(".vpc-card");
      const cardStyle = card ? getComputedStyle(card) : null;
      return {
        topPosition: top.position,
        playPosition: playStyle?.position ?? "missing",
        radius: cardStyle?.borderRadius ?? "",
        title: document.querySelector(".vpc-title")?.textContent ?? "",
      };
    });
    if (layout.topPosition !== "absolute" || layout.playPosition !== "absolute") {
      throw new Error(`video chrome is not overlaid: ${JSON.stringify(layout)}`);
    }
    if (!String(layout.radius).startsWith("16")) {
      throw new Error(`video card radius is ${layout.radius}`);
    }
    await page.locator(".vpc-stage").first().hover();
    await page.waitForTimeout(400);
    const path = join(outDir, `video-widgets-${label}.png`);
    await page.screenshot({ path, fullPage: true });
    console.log(`wrote ${path}`);

    // the expanded view on its own page (it covers the viewport)
    await page.goto(`${base}?skin=${id}&expanded=1`, { waitUntil: "load", timeout: 120_000 });
    const expanded = await page.waitForSelector('.vpc-card[data-expanded="true"]', { timeout: 30_000 }).catch(() => null);
    if (expanded) {
      await page.setViewportSize({ width: 1280, height: 800 });
      await page.locator(".vpc-stage").first().hover();
      await page.waitForTimeout(400);
      const expandedPath = join(outDir, `video-expanded-${label}.png`);
      await page.screenshot({ path: expandedPath });
      console.log(`wrote ${expandedPath}`);
      await page.setViewportSize({ width: 920, height: 1400 });
    }
  }

  await browser.close();
  await writeFile(join(outDir, "README.txt"), "Generated by scripts/capture/video-widgets.mjs\n");
} finally {
  try {
    process.kill(-vite.pid, "SIGTERM");
  } catch {
    vite.kill("SIGTERM");
  }
  if (vite.exitCode === null) {
    await new Promise((r) => vite.once("exit", r));
  }
  if (vite.exitCode && vite.exitCode !== 0 && !viteLog.includes(port)) {
    console.error(viteLog);
  }
}
