#!/usr/bin/env node
/**
 * #2091: headless screenshots of the "Always allow" action on cards that
 * had none (a rule proposal), of a card the organization keeps to one answer
 * (plain words, Perspicax link), of an engine card with its rule and of a
 * Pulsatrix Flow GO card (#2091, the reported example).
 * Synthetic data only. Headless Chromium: no window opens.
 * Usage: node scripts/capture/always-allow-cards.mjs [--out DIR] [--port N]
 */
import { spawn } from "node:child_process";
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..");
const arg = (name) => { const index = process.argv.indexOf(name); return index >= 0 ? process.argv[index + 1] : undefined; };
const outDir = resolve(arg("--out") ?? join(root, "docs", "screenshots", "always-allow-cards"));
const port = Number(arg("--port") ?? 5283);
const shots = [
  { page: "rule-request", query: { card: "add", behavior: "allow" }, selector: '[data-shot="rule-request"]', name: "rule-request-add" },
  { page: "approval-card", query: { card: "command" }, selector: '[data-shot="approval-card"]', name: "engine-command" },
  { page: "approval-card", query: { card: "org-once" }, selector: '[data-shot="approval-card"]', name: "org-ask-first" },
  // the reported example: a Pulsatrix Flow GO for one ConnectWise write
  { page: "approval-card", query: { card: "flow-go" }, selector: '[data-shot="approval-card"]', name: "flow-go" },
];

async function waitForServer(url, ms = 120_000) {
  const start = Date.now();
  while (Date.now() - start < ms) {
    try { if ((await fetch(url)).status < 500) return; } catch { /* retry */ }
    await new Promise((done) => setTimeout(done, 500));
  }
  throw new Error(`gallery did not start at ${url}`);
}

const vite = spawn("pnpm", ["exec", "vite", "--config", "vite.gallery.config.ts", "--host", "127.0.0.1", "--port", String(port), "--strictPort"], {
  cwd: root, stdio: ["ignore", "pipe", "pipe"], env: { ...process.env, NODE_ENV: "development" },
  detached: true,
});
let log = "";
vite.stdout?.on("data", (chunk) => { log += chunk; });
vite.stderr?.on("data", (chunk) => { log += chunk; });

let browser;
try {
  const base = `http://127.0.0.1:${port}/src/gallery/`;
  await waitForServer(`${base}rule-request.html`);
  const { chromium } = await import(process.env.SAGAX_VERIFY_PLAYWRIGHT || "playwright");
  await mkdir(outDir, { recursive: true });
  browser = await chromium.launch({
    headless: true,
    ...(process.env.SAGAX_VERIFY_BROWSER_CHROME ? { executablePath: process.env.SAGAX_VERIFY_BROWSER_CHROME } : {}),
  });
  const page = await browser.newPage({ viewport: { width: 780, height: 720 }, deviceScaleFactor: 2 });
  const found = {};
  for (const lang of ["en", "fr"]) {
    for (const shot of shots) {
      const query = new URLSearchParams({ skin: "daylight", lang, ...shot.query });
      await page.goto(`${base}${shot.page}.html?${query}`, { waitUntil: "load" });
      await page.waitForSelector(shot.selector);
      await page.waitForTimeout(400);
      await page.locator(shot.selector).screenshot({ path: join(outDir, `${shot.name}-${lang}.png`) });
      found[`${shot.name}-${lang}`] = {
        alwaysAllow: await page.locator(shot.selector).getByText(/always allow|toujours permettre/i).count(),
        orgOnce: await page.locator('[data-org-always-allow-off]').count(),
      };
    }
  }
  await writeFile(join(outDir, "found.json"), `${JSON.stringify(found, null, 2)}\n`);
  await writeFile(join(outDir, "README.md"), `# Always allow on every card (#2091)

Synthetic gallery captures: a rule proposal with its Always allow, an engine
command card with its rule, a Pulsatrix Flow GO card (the write named, its
arguments folded once, Always allow for that tool and action) and the one
card without it (the organization's Ask first policy, with the way to Perspicax).
Generated by \`node scripts/capture/always-allow-cards.mjs\`. No real person data.
`);
  console.log(`screenshots in ${outDir}`);
  console.log(JSON.stringify(found));
} catch (error) {
  console.error(error instanceof Error ? error.message : String(error));
  if (log) console.error(log.slice(-2000));
  process.exitCode = 1;
} finally {
  await browser?.close().catch(() => {});
  try { process.kill(-vite.pid, "SIGTERM"); } catch { /* already gone */ }
}
