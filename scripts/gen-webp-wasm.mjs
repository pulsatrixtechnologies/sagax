// Regenerate server/webp-wasm.generated.ts from the installed @jsquash/webp.
//   node scripts/gen-webp-wasm.mjs          write the file
//   node scripts/gen-webp-wasm.mjs --check  fail when the file is stale
// Run it after bumping @jsquash/webp in package.json.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { gzipSync } from "node:zlib";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const WASM = join(root, "node_modules", "@jsquash", "webp", "codec", "dec", "webp_dec.wasm");
const OUT = join(root, "server", "webp-wasm.generated.ts");

export function version() {
  return JSON.parse(readFileSync(join(root, "node_modules", "@jsquash", "webp", "package.json"), "utf8")).version;
}

export function render(wasm, packageVersion) {
  const base64 = gzipSync(wasm, { level: 9, mtime: 0 }).toString("base64");
  const lines = base64.match(/.{1,120}/g) ?? [];
  return `// WebP decoder (libwebp, Google, BSD-3-Clause) compiled to WebAssembly, as
// shipped by @jsquash/webp ${packageVersion} (Apache-2.0) in codec/dec/webp_dec.wasm.
// sha256 of the raw .wasm: ${createHash("sha256").update(wasm).digest("hex")}
// The server is an esbuild bundle with no node_modules at runtime, so the
// binary travels inline (gzip + base64) and is instantiated from memory by
// server/webp-decode.ts. GENERATED by scripts/gen-webp-wasm.mjs: do not edit.
export const WEBP_DEC_WASM_GZ_BASE64 =
  "${lines.join('" +\n  "')}";
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const next = render(readFileSync(WASM), version());
  if (process.argv.includes("--check")) {
    if (readFileSync(OUT, "utf8") !== next) {
      console.error("server/webp-wasm.generated.ts is stale: run node scripts/gen-webp-wasm.mjs");
      process.exit(1);
    }
  } else {
    writeFileSync(OUT, next);
  }
}
