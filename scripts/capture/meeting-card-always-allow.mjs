#!/usr/bin/env node
/**
 * #3367: headless screenshots of Always allow on the meeting join card.
 * Synthetic data only. Headless Chromium: no window opens.
 * Usage: node scripts/capture/meeting-card-always-allow.mjs [--out DIR] [--port N]
 */
import { spawn } from "node:child_process";
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..");
const arg = (name) => { const index = process.argv.indexOf(name); return index >= 0 ? process.argv[index + 1] : undefined; };
const outDir = resolve(arg("--out") ?? join(root, "docs", "screenshots", "meeting-card-always-allow"));
const port = Number(arg("--port") ?? 5287);

async function waitForServer(url, ms = 120_000) {
  const start = Date.now();
  while (Date.now() - start < ms) {
    try { if ((await fetch(url)).status < 500) return; } catch { /* retry */ }
    await new Promise((done) => setTimeout(done, 500));
  }
  throw new Error(`gallery did not start at ${url}`);
}

const vite = spawn("pnpm", ["exec", "vite", "--config", "vite.gallery.config.ts", "--host", "127.0.0.1", "--port", String(port), "--strictPort"], {
  cwd: root, stdio: ["ignore", "pipe", "pipe"], env: { ...process.env, NODE_ENV: "development" },
  detached: true,
});
let log = "";
vite.stdout?.on("data", (chunk) => { log += chunk; });
vite.stderr?.on("data", (chunk) => { log += chunk; });

let browser;
try {
  const base = `http://127.0.0.1:${port}/src/gallery/`;
  await waitForServer(`${base}meeting-card.html`);
  const { chromium } = await import(process.env.SAGAX_VERIFY_PLAYWRIGHT || "playwright");
  await mkdir(outDir, { recursive: true });
  browser = await chromium.launch({
    channel: "chrome",
    headless: true,
    ...(process.env.SAGAX_VERIFY_BROWSER_CHROME ? { executablePath: process.env.SAGAX_VERIFY_BROWSER_CHROME } : {}),
  });
  const page = await browser.newPage({ viewport: { width: 720, height: 900 }, deviceScaleFactor: 2 });
  const found = {};
  for (const lang of ["en", "fr"]) {
    for (const skin of ["daylight", "midnight"]) {
      const query = new URLSearchParams({ skin, lang, state: "pending" });
      await page.goto(`${base}meeting-card.html?${query}`, { waitUntil: "load" });
      await page.waitForSelector('[data-shot="meeting-card"]');
      await page.waitForSelector("[data-always-allow]");
      await page.waitForTimeout(400);
      const name = `meeting-pending-${skin}-${lang}`;
      await page.locator('[data-shot="meeting-card"]').screenshot({ path: join(outDir, `${name}.png`) });
      found[name] = {
        alwaysAllow: await page.locator("[data-always-allow]").count(),
      };
    }
  }
  await writeFile(join(outDir, "found.json"), `${JSON.stringify(found, null, 2)}\n`);
  await writeFile(join(outDir, "README.md"), `# Meeting join card Always allow (#3367)

Synthetic gallery captures of the consent card with Always allow for that
provider (clair daylight, sombre midnight; en and fr). Generated by
\`node scripts/capture/meeting-card-always-allow.mjs\`. No real person data.
`);
  console.log(`screenshots in ${outDir}`);
  console.log(JSON.stringify(found));
} catch (error) {
  console.error(error);
  console.error(log.slice(-4_000));
  process.exitCode = 1;
} finally {
  await browser?.close().catch(() => {});
  if (vite.pid) {
    try { process.kill(-vite.pid, "SIGTERM"); } catch { try { vite.kill("SIGTERM"); } catch { /* done */ } }
  }
}
