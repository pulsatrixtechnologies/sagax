#!/usr/bin/env node
/**
 * Headless screenshots for Shape engine v2 object silhouettes
 * (docs/screenshots/shape-engine-v2/). Playwright + vite gallery, headless only.
 */
import { spawn } from "node:child_process";
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = resolve(process.argv.includes("--out")
  ? process.argv[process.argv.indexOf("--out") + 1]
  : join(root, "docs", "screenshots", "shape-engine-v2"));
const port = Number(process.argv.includes("--port")
  ? process.argv[process.argv.indexOf("--port") + 1]
  : 5298);

const OBJECTS = ["pad", "cup", "bulb", "say", "sprout", "tin", "tome", "ship"];
/** Display sizes the brief asks to evidence (gallery `size` is CSS px; 28/48/96). */
const SIZES = [28, 48, 96];
const scenes = [
  ...SIZES.flatMap((size) =>
    OBJECTS.map((id) => ({ name: `object-${id}-${size}`, query: `size=${size}&only=${id}&still=1` })),
  ),
  { name: "objects-row-96", query: "size=72&still=1" },
  { name: "mood-happy-cup", query: "size=96&only=cup&mood=happy&still=1" },
  { name: "mood-thinking-bulb", query: "size=96&only=bulb&mood=thinking&still=1" },
  { name: "mood-sleep-say", query: "size=96&only=say&mood=sleeping&still=1" },
  ...SIZES.map((size) => ({ name: `neighbor-circle-${size}`, query: `size=${size}&only=circle&still=1` })),
  ...SIZES.map((size) => ({ name: `neighbor-bean-${size}`, query: `size=${size}&only=bean&still=1` })),
];

function waitForServer(url, ms = 60_000) {
  const start = Date.now();
  return new Promise((resolveWait, reject) => {
    const tick = async () => {
      try {
        const res = await fetch(url);
        if (res.ok || res.status === 404) return resolveWait();
      } catch {
        // keep waiting
      }
      if (Date.now() - start > ms) return reject(new Error(`server not ready: ${url}`));
      setTimeout(tick, 400);
    };
    void tick();
  });
}

const vite = spawn("pnpm", ["exec", "vite", "--config", "vite.gallery.config.ts", "--host", "127.0.0.1", "--port", String(port), "--strictPort"], {
  cwd: root,
  stdio: ["ignore", "pipe", "pipe"],
  env: { ...process.env, NODE_ENV: "development" },
  detached: true,
});

try {
  const base = `http://127.0.0.1:${port}/src/gallery/shape-set.html`;
  await waitForServer(base);
  const { chromium } = await import(process.env.SAGAX_VERIFY_PLAYWRIGHT || "playwright");
  await mkdir(outDir, { recursive: true });
  const chrome = process.env.SAGAX_VERIFY_BROWSER_CHROME
    || "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome";
  const browser = await chromium.launch({ headless: true, executablePath: chrome });
  const warm = await browser.newPage();
  await warm.goto(`${base}?skin=pulsatrix-light&size=44&only=pad&still=1`, { waitUntil: "networkidle" });
  await warm.waitForTimeout(1200);
  await warm.close();

  for (const scene of scenes) {
    const context = await browser.newContext({ viewport: { width: 900, height: 520 }, deviceScaleFactor: 2 });
    const page = await context.newPage();
    const file = join(outDir, `${scene.name}.png`);
    await page.goto(`${base}?skin=pulsatrix-light&${scene.query}`, { waitUntil: "load" });
    await page.waitForSelector("[data-shot]");
    await page.waitForTimeout(500);
    await page.locator("[data-shot]").screenshot({ path: file });
    await context.close();
    console.log("wrote", scene.name);
  }
  await browser.close();
  await writeFile(
    join(outDir, "README.md"),
    `# Shape engine v2.1 screenshots

Headless captures of path-bodied object silhouettes (pad with grips, cup with
handle, bulb with base, say with tail, sprout with leaves, tin with spout,
tome, ship) beside neighboring polar catalog shapes (circle, bean). Generated by
\`node scripts/capture-shape-engine-v2.mjs\` against \`src/gallery/shape-set.html\`.

Sizes: \`object-*-28.png\`, \`object-*-48.png\`, \`object-*-96.png\` (readable
appendages at each). Compare with \`neighbor-circle-*\` / \`neighbor-bean-*\`
at the same sizes: same volume treatment, pill eyes on the body, no
disassembly, no GUID labels in the UI.

Moods: \`mood-happy-cup\`, \`mood-thinking-bulb\`, \`mood-sleep-say\`.

Path bodies are an additional body kind; the polar 40-shape catalog stays.
`,
  );
  console.log("done", outDir);
} finally {
  try {
    process.kill(-vite.pid, "SIGTERM");
  } catch {
    vite.kill("SIGTERM");
  }
}
