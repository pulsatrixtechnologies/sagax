#!/usr/bin/env node
/**
 * Headless screenshots of routines in the side panel (JC, 2026-11-01):
 * routine detail, panel edit, and run-as-exchange. Sizes 1338x809 and
 * 700x809, dark and light. Headless Chromium only; no window opens.
 * Usage: node scripts/capture-routines-in-sidebar.mjs [--out DIR] [--port N]
 */
import { spawn } from "node:child_process";
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const arg = (name, fallback) => {
  const index = process.argv.indexOf(name);
  return index >= 0 ? process.argv[index + 1] : fallback;
};
const outDir = resolve(arg("--out", join(root, "docs", "screenshots", "routines-in-sidebar")));
const port = Number(arg("--port", "5311"));
const skins = [
  { id: "pulsatrix", label: "dark" },
  { id: "pulsatrix-light", label: "light" },
];
const sizes = [
  { width: 1338, height: 809, label: "desktop" },
  { width: 700, height: 809, label: "narrow" },
];
const views = ["detail", "edit", "run"];

async function waitForServer(url, ms = 120_000) {
  const start = Date.now();
  while (Date.now() - start < ms) {
    try {
      if ((await fetch(url)).status < 500) return;
    } catch {
      /* retry */
    }
    await new Promise((done) => setTimeout(done, 500));
  }
  throw new Error(`gallery did not start at ${url}`);
}

const vite = spawn(
  "pnpm",
  ["exec", "vite", "--config", "vite.gallery.config.ts", "--host", "127.0.0.1", "--port", String(port), "--strictPort"],
  { cwd: root, stdio: ["ignore", "pipe", "pipe"], env: { ...process.env, NODE_ENV: "development" }, detached: true },
);
let log = "";
vite.stdout?.on("data", (chunk) => { log += chunk; });
vite.stderr?.on("data", (chunk) => { log += chunk; });

let browser;
try {
  const base = `http://127.0.0.1:${port}/src/gallery/routines-in-sidebar.html`;
  await waitForServer(base);
  const { chromium } = await import(process.env.SAGAX_VERIFY_PLAYWRIGHT || "playwright");
  await mkdir(outDir, { recursive: true });
  browser = await chromium.launch({
    headless: true,
    ...(process.env.SAGAX_VERIFY_BROWSER_CHROME
      ? { executablePath: process.env.SAGAX_VERIFY_BROWSER_CHROME }
      : process.env.SAGAX_CHROMIUM
        ? { executablePath: process.env.SAGAX_CHROMIUM }
        : { channel: "chrome" }),
  });
  for (const size of sizes) {
    for (const skin of skins) {
      for (const view of views) {
        const page = await browser.newPage({ viewport: { width: size.width, height: size.height }, deviceScaleFactor: 2 });
        const url = `${base}?view=${view}&skin=${skin.id}&width=${size.width}&height=${size.height}&lang=en`;
        await page.goto(url, { waitUntil: "domcontentloaded" });
        const ready = view === "run"
          ? "[data-testid=routine-run-exchange]"
          : view === "edit"
            ? "[data-routine-editor-presentation=panel]"
            : "[data-routine-detail]";
        await page.waitForSelector(ready, { timeout: 60_000 });
        await page.waitForTimeout(800);
        const file = join(outDir, `after-${view}-${size.label}-${skin.label}.png`);
        await page.screenshot({ path: file });
        const visible = await page.locator("[data-gallery-sample]").innerText({ timeout: 5_000 }).catch(() => "");
        if (visible && /\b[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\b/i.test(visible)) {
          throw new Error(`raw GUID visible in ${view} ${size.label} ${skin.label}`);
        }
        console.log(file);
        await page.close();
      }
    }
  }
  const readme = `# Routines in the side panel (2026-11-01)

JC decision: routine screens behave like Grok Bot, inside the right side panel
or the chat column, never as centered modal windows.

## Captures

Sizes: 1338x809 (desktop) and 700x809 (narrow). Skins: pulsatrix (dark) and
pulsatrix-light (light). Generated by \`node scripts/capture-routines-in-sidebar.mjs\`.

| File | What it shows |
| --- | --- |
| after-detail-desktop-dark.png | Routine detail in the bot panel (Trigger, Next run, Runs, actions) |
| after-detail-desktop-light.png | Same, light skin |
| after-detail-narrow-dark.png | Same, narrow width |
| after-detail-narrow-light.png | Same, narrow + light |
| after-edit-desktop-dark.png | Edit routine as a panel push (Back, name, What / When / Where, More, Save) |
| after-edit-desktop-light.png | Same, light |
| after-edit-narrow-dark.png | Same, narrow |
| after-edit-narrow-light.png | Same, narrow + light |
| after-run-desktop-dark.png | Run view as exchange sheet in the chat column (routine <-> bot, bubbles, Close Chat) |
| after-run-desktop-light.png | Same, light |
| after-run-narrow-dark.png | Same, narrow |
| after-run-narrow-light.png | Same, narrow + light |

## Neighbours

Compare with \`docs/screenshots/bot-exchange-sheet/\` (Melonie <-> Katarina style)
and \`docs/screenshots/routines-ux/\` / \`view-run/\` for the previous modal run
detail. Raw ids and GUIDs must never appear in the visible UI.
`;
  await writeFile(join(outDir, "README.md"), readme);
  console.log(join(outDir, "README.md"));
} catch (error) {
  console.error(error);
  console.error(log.slice(-4000));
  process.exitCode = 1;
} finally {
  await browser?.close();
  try { process.kill(-vite.pid, "SIGTERM"); } catch { /* gone */ }
}
