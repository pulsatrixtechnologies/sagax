// Writes server/tool-policy.generated.ts: one row per route in the inventory.
// A row already in the table keeps its reviewed fields; a new route gets the
// default classification; a row whose route is gone is dropped.
//   node scripts/tool-policy/generate.ts
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { routeInventory } from "./route-inventory.ts";
import { classifyRoute, policyKey, toolPolicyRows, type ToolPolicy } from "../../server/tool-policy.ts";

const root = fileURLToPath(new URL("../..", import.meta.url));
const existing = new Map(toolPolicyRows().map((row) => [policyKey(row), row]));
// A route whose method guard the inventory now reads (ANY became GET and
// POST) keeps the review of its old row: a tier, scope or defaultEnabled
// someone chose must not fall back to the default because a line moved.
const fields = ({ method: _m, kind: _k, route: _r, readOnly: _o, ...rest }: ToolPolicy | (ReturnType<typeof classifyRoute> & { method?: string; kind?: string; route?: string })) => JSON.stringify(rest);
const byRoute = new Map(toolPolicyRows()
  .filter((row) => row.method === "ANY" && fields(row) !== fields(classifyRoute("ANY", row.route)))
  .map((row) => [`${row.kind} ${row.route}`, row]));
const rows: ToolPolicy[] = routeInventory(root).map(({ kind, route, method }) => {
  const same = existing.get(policyKey({ method, kind, route }));
  if (same) return same;
  const fresh = classifyRoute(method, route);
  const reviewed = byRoute.get(`${kind} ${route}`);
  if (!reviewed) return { method, kind, route, ...fresh };
  const { method: _m, kind: _k, route: _r, readOnly: _o, ...kept } = reviewed;
  return { method, kind, route, ...fresh, ...kept, readOnly: method === "GET" && fresh.readOnly };
});
const body = rows.map((row) => `  ${JSON.stringify(row)},`).join("\n");
writeFileSync(new URL("../../server/tool-policy.generated.ts", import.meta.url),
  `// Generated by scripts/tool-policy/generate.ts, then reviewed: edit a row's tier,\n// scope or defaultEnabled here; rerun the script when routes change.\nimport type { ToolPolicy } from "./tool-policy-types.ts";\n\nexport const TOOL_POLICY_ROWS: readonly ToolPolicy[] = [\n${body}\n];\n`);
console.log(`${rows.length} rows`);
