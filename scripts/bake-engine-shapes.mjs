#!/usr/bin/env node
/**
 * Bake every body shape of the app into an avatar definition of the
 * open-bot-avatar engine (MIT, see NOTICE): shared/shape-avatars.json (#4145).
 *
 * A shape the engine's examples or gallery already draw (the star, the mug,
 * the rocket...) points at that definition by id: the same object, the
 * engine's outline. The others are our own bodies from
 * shared/mascot-geometry.json (the 64 radii drawn as shape-art.ts draws them,
 * the pumpkin with its stem; an object's path), fitted into the engine's
 * 0 0 100 100 box with room to turn (its safe area is 8..92), the eyes
 * centred across the face. The engine's gallery is copied verbatim in
 * third_party/open-bot-avatar/gallery.
 *
 * Then every shape's still (each of the engine's moods, at rest) is baked
 * into src/components/shape-stills/<id>.json: the engine infers a body's
 * volume here, once, never on the page for a sidebar of bots. Run:
 *   node scripts/bake-engine-shapes.mjs
 * then src/components/shape-avatar.test.ts validates every definition and
 * checks every still against the engine.
 */
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { FACE_ANCHOR, outlinePath, SHAPE_RADII, stemPath } from "../src/components/shape-art.ts";
import { boxFit, fitPath, flattenPath } from "../shared/shape-avatar-outline.ts";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const geometry = JSON.parse(readFileSync(join(root, "shared/mascot-geometry.json"), "utf8"));
const gallery = new Set(readdirSync(join(root, "third_party/open-bot-avatar/gallery")).map((file) => file.replace(/\.json$/, "")));

/** Shapes the engine already draws: shape id -> the engine's id (an example built into the package, or a gallery file). */
const ENGINE_SHAPES = {
  star: "star",
  cloud: "cloud",
  ghost: "ghost",
  cat: "cat",
  shield: "shield",
  pad: "controller",
  cup: "mug",
  bulb: "lightbulb",
  say: "chat",
  sprout: "sprout",
  tome: "book",
  ship: "rocket",
};

/** The engine's examples built into the package (getExample). */
const EXAMPLES = new Set(["controller", "barbell", "mug", "lightbulb", "chat", "sprout", "watering-can"]);

/** Our eyes in the engine's terms: centre to centre, and their size (1 = 4 by 11 units). */
const EYES = { spacing: 17, scale: 1.15 };
const round = (value) => Math.round(value * 100) / 100;

function ownDefinition(id, entry) {
  const name = id.charAt(0).toUpperCase() + id.slice(1);
  // an object's own path and its eyes' anchor, else the radii (and the pumpkin's stem) as the app drew them
  const body = entry.path ?? outlinePath(SHAPE_RADII[id]) + (id === "pumpkin" ? stemPath(SHAPE_RADII[id]) : "");
  const fit = boxFit(flattenPath(body).flat());
  // the engine turns the body itself: the pair sits across the middle, a little under it as on our faces
  const [x, y] = entry.path ? fit.at(entry.eyes.anchor) : fit.at([50, 50 + FACE_ANCHOR[id][1] * 0.6 * geometry.box.unit]);
  return {
    version: 1,
    id,
    name,
    body: { path: fitPath(body, fit) },
    eyes: { x: round(x), y: round(y), spacing: round(EYES.spacing * Math.min(1, fit.scale)), scale: EYES.scale },
  };
}

const shapes = {};
for (const [id, entry] of Object.entries(geometry.shapes)) {
  const engine = ENGINE_SHAPES[id];
  if (engine && !EXAMPLES.has(engine) && !gallery.has(engine)) throw new Error(`${id}: no engine definition ${engine}`);
  shapes[id] = engine ? { engine } : { own: ownDefinition(id, entry) };
}

const out = {
  note: "Generated by scripts/bake-engine-shapes.mjs from shared/mascot-geometry.json; do not edit. Each body shape of the app as an open-bot-avatar definition (the engine's docs/avatar-contract.md): `engine` names one of the engine's examples or gallery definitions (third_party/open-bot-avatar/gallery, MIT), `own` is our own body in the same spec. The engine's other avatars are shapes of their own under their engine id (shared/mascot-look.ts GALLERY_SHAPES).",
  shapes,
};
writeFileSync(join(root, "shared/shape-avatars.json"), `${JSON.stringify(out, null, 1)}\n`);
console.log(`${Object.keys(shapes).length} shapes`);

// the stills, from the definitions just written (shape-avatar.ts reads them)
const { bakeStill, shapeDefinition } = await import("../src/components/shape-avatar.ts");
const { MASCOT_SHAPES } = await import("../shared/mascot-look.ts");
const stills = join(root, "src/components/shape-stills");
rmSync(stills, { recursive: true, force: true });
mkdirSync(stills, { recursive: true });
for (const shape of MASCOT_SHAPES) writeFileSync(join(stills, `${shape}.json`), `${JSON.stringify(bakeStill(shapeDefinition(shape)))}\n`);
console.log(`${MASCOT_SHAPES.length} stills`);
