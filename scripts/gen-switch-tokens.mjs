#!/usr/bin/env node
// Writes src/styles/skin-switch.css: the switch's track colours for every
// skin, colour, Full colour, duo-tone, mood and Windows edition, derived by
// src/lib/switch-colors.ts from the tokens each block resolves to (read with
// the contrast script's own parser, so nothing is copied by hand).
//
//   pnpm gen:switch          # rewrite the stylesheet after a palette change
//
// src/lib/switch-colors.test.ts fails while the file is out of date, and
// below 3:1 for any thumb, track or edge.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { skinIds, skinTokens } from "./check-skin-contrast.mjs";
import { switchColors } from "../src/lib/switch-colors.ts";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
export const SWITCH_CSS = join(ROOT, "src/styles/skin-switch.css");

/** The surfaces a switch is drawn on: settings pages and cards, raised rows, menus and popovers. */
export const SWITCH_SURFACES = ["--color-app", "--color-panel", "--color-card", "--color-raised", "--color-menu", "--color-popover", "--color-inset"];

/** The stylesheets the contrast script measures, in its own order. */
export function stylesheets() {
  let css = readFileSync(join(ROOT, "src/styles.css"), "utf8");
  for (const name of ["depth", "duo", "ambiance", "texture"]) css += "\n" + readFileSync(join(ROOT, `src/styles/skin-${name}.css`), "utf8");
  const editions = join(ROOT, "src/styles/retro-editions");
  for (const file of readdirSync(editions).filter((name) => name.endsWith(".css")).sort()) css += "\n" + readFileSync(join(editions, file), "utf8");
  return css;
}

const OPAQUE = /^#[0-9a-f]{6}$/i;

function luminance(hex) {
  const c = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255).map((s) => (s <= 0.04045 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4));
  return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2];
}

/** One context per skin block: its selector, the surfaces measured, the scheme and the colours. */
export function switchContexts(css = stylesheets()) {
  return skinIds(css).map((id) => {
    const tokens = skinTokens(css, id) ?? {};
    const surfaces = SWITCH_SURFACES.map((name) => tokens[name]).filter((value) => value && OPAQUE.test(value));
    const app = tokens["--color-app"] ?? "#ffffff";
    const scheme = luminance(app) < 0.2 ? "dark" : "light";
    const [skin, tint, full] = id.split("+");
    const selector = `[data-skin="${skin}"]` + (tint ? `[data-skin-tint="${tint}"]` : "") + (full ? `[data-skin-depth="full"]` : "");
    const colors = switchColors({ accent: tokens["--color-accent"] ?? app, ink: tokens["--color-ink"] ?? "#000000", surfaces, scheme });
    return { id, selector, scheme, surfaces, colors };
  });
}

/** The stylesheet text. */
export function switchStylesheet(css = stylesheets()) {
  const block = ({ selector, colors: c }) => {
    return `${selector} {\n  --color-switch-on: ${c.on};\n  --color-switch-off: ${c.off};\n  --color-switch-on-edge: ${c.onEdge};\n  --color-switch-off-edge: ${c.offEdge};\n}\n`;
  };
  const contexts = switchContexts(css);
  const fallback = contexts.find((c) => c.id === "pulsatrix");
  const lines = [
    "/* GENERATED by scripts/gen-switch-tokens.mjs from the skin blocks: do not edit.",
    "   The switch's tracks for every skin and variant (src/lib/switch-colors.ts):",
    "   a white thumb on both, 3:1 between thumb and track and between the track",
    "   (or its edge) and the surfaces it sits on. `pnpm gen:switch` rewrites it. */",
    "",
    fallback ? block({ ...fallback, selector: ":root" }) : "",
    ...contexts.map(block),
  ];
  return lines.join("\n");
}

const isMain = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;
if (isMain) {
  writeFileSync(SWITCH_CSS, switchStylesheet());
  console.log(`wrote ${SWITCH_CSS}`);
}
